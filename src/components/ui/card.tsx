  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement>
>(({ className, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[10px] border bg-card text-card-foreground shadow-sm",
      className
    )}
    {...props}
  />
))
